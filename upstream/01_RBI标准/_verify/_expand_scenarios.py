def mk(sid, kind, plant, equip, eq, mat, meds, temp, evid, q, tools, target=None):
    r = tools_mod.damage_mechanism_query(material=mat, medium=meds, temperature_c=temp,
                                        equipment_type=eq)
    mechs = [x['name'] for x in (r['result'].get('mechanisms') or [])] if r['result'] else []
    d = {
        'sid': sid, 'kind': kind, 'plant': plant, 'equipment': equip,
        'equipment_type': eq, 'material': mat, 'medium': meds,
        'temperature_c': temp, 'field_evidence': evid, 'question': q,
        'tools': tools, 'expect_mechs': mechs,
        'actual_status': r['status'],
        'has_discriminator': bool(r['result'].get('discriminator')) if r['result'] else False,
    }
    if target:
        d['target_mech'] = target
    return d


