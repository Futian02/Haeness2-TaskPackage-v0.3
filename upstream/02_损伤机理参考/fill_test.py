def main():
    wb = openpyxl.load_workbook(PATH)
    ws = wb["摘录表"]
    # 找最后一个有数据的行（在前25列里任一格有值即算）
    last = ws.max_row
    while last > 1 and all(ws.cell(last, c).value in (None, "") for c in range(1, len(COLS) + 1)):
        last -= 1
    r = last + 1
    print("最后一个有数据的行:", last, "-> 追加到第", r, "行")

    excerpt = DATA.get("原文摘录") or ""
    if len(excerpt) > 300:
        raise SystemExit(f"原文摘录 {len(excerpt)} 字，超过300，先删减！")

    values = {
        **{k: DATA.get(k) for k in COLS},
        "抽取人": WHO, "复核人": None, "备注": REMARK,
    }
    for c, key in enumerate(COLS, start=1):
        src = ws.cell(last, c)  # 样式复制自最后一个有数据的行
        dst = ws.cell(r, c)
        dst.value = values.get(key)
        dst.font = copy.copy(src.font)
        dst.border = copy.copy(src.border)
        dst.fill = copy.copy(src.fill)
        dst.alignment = copy.copy(src.alignment)
        if key == "clause_no":
            dst.number_format = "@"
    print("written", r, values["clause_id"], values["title"], "| 摘录", len(excerpt), "字")
    wb.save(PATH)
    print("saved", PATH)


if __name__ == "__main__":
    main()
