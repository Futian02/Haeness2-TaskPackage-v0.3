    for i, data in enumerate(ROWS):
        # 原文摘录长度自检（≤300）
        excerpt = data.get("原文摘录") or ""
        if len(excerpt) > 300:
            raise SystemExit(f"{data['clause_id']} 原文摘录 {len(excerpt)} 字，超过300，先删减！")
        r = start + i
        values = {
            **{k: data.get(k) for k in COLS},
            "抽取人": WHO, "复核人": None, "备注": REMARK,
        }
        for c, key in enumerate(COLS, start=1):
            src = ws.cell(14, c)
            dst = ws.cell(r, c)
            dst.value = values.get(key)
            dst.font = copy.copy(src.font)
            dst.border = copy.copy(src.border)
            dst.fill = copy.copy(src.fill)
            dst.alignment = copy.copy(src.alignment)
